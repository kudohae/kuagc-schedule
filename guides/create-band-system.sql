create or replace function public.set_band_song_note(p_song_id bigint, p_note text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  update public.band_songs s
  set note = coalesce(p_note, '')
  where s.id = p_song_id
    and exists (
      select 1
      from public.band_rounds r
      where r.id = s.round_id
        and r.is_active
    );

  if not found then
    raise exception 'Active band song not found';
  end if;
end;
$$;

revoke all on function public.set_band_song_note(bigint, text) from public;
grant execute on function public.set_band_song_note(bigint, text) to anon, authenticated;

-- Create the first band round from the newest regular ensemble round.
insert into public.band_rounds (name, is_active, song_application_open, session_application_open)
select er.name, true, false, false
from public.ensemble_rounds er
where er.type = 'regular'
order by er.created_at desc
limit 1
on conflict do nothing;

-- Copy the current song list once. Re-running this file does not duplicate it.
insert into public.band_songs (
  round_id, title, artist, applicant_name, student_id, wanted_roles, note,
  is_formed, source_song_id, created_at
)
select
  br.id, sa.title, sa.artist, sa.applicant_name, sa.student_id,
  coalesce(sa.sessions, '{}'), coalesce(sa.public_note, ''),
  coalesce(sa.is_formed, false), sa.id, sa.created_at
from public.song_applications sa
join public.ensemble_rounds er on er.id = sa.round_id
join public.band_rounds br on br.name = er.name and br.is_active
where er.id = (
  select id from public.ensemble_rounds
  where type = 'regular'
  order by created_at desc
  limit 1
)
and sa.status <> 'rejected'
on conflict (source_song_id) do nothing;

-- Closed rounds expose confirmed applicants only; preserve their exact timestamps.
insert into public.band_members (
  song_id, applicant_name, student_id, roles, source_application_id, created_at
)
select
  bs.id, app.applicant_name, app.student_id, coalesce(app.sessions, '{}'),
  app.id, app.created_at
from public.session_applications app
join public.band_songs bs on bs.source_song_id = app.song_id
where app.status = 'confirmed'
on conflict (source_application_id) do nothing;
