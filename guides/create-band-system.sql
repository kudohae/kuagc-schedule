-- Independent, flexible band application system.
-- Existing ensemble tables are read only for the one-time initial snapshot below.

create table if not exists public.band_rounds (
  id bigint generated by default as identity primary key,
  name text not null check (btrim(name) <> ''),
  is_active boolean not null default false,
  song_application_open boolean not null default false,
  session_application_open boolean not null default false,
  is_blinded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists band_rounds_one_active_idx
  on public.band_rounds (is_active)
  where is_active;

create table if not exists public.band_songs (
  id bigint generated by default as identity primary key,
  round_id bigint not null references public.band_rounds(id) on delete cascade,
  title text not null check (btrim(title) <> ''),
  artist text not null check (btrim(artist) <> ''),
  applicant_name text not null check (btrim(applicant_name) <> ''),
  student_id text not null check (btrim(student_id) <> ''),
  wanted_roles text[] not null default '{}',
  note text not null default '',
  is_formed boolean not null default false,
  source_song_id bigint unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists band_songs_round_created_idx
  on public.band_songs (round_id, created_at, id);

create table if not exists public.band_members (
  id bigint generated by default as identity primary key,
  song_id bigint not null references public.band_songs(id) on delete cascade,
  applicant_name text not null check (btrim(applicant_name) <> ''),
  student_id text not null check (btrim(student_id) <> ''),
  roles text[] not null default '{}',
  note text not null default '',
  is_included boolean not null default true,
  source_application_id bigint unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists band_members_song_created_idx
  on public.band_members (song_id, created_at, id);

create or replace function public.set_band_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

